def number(value):
    return format(value, '.6g')


def block(key, values):
    return f'{key} = {{ ' + ' '.join(f'{k} = {number(v)}' for k, v in values.items()) + ' }'


def completed(focuses):
    terms = ' '.join('has_completed_focus = ' + fid for fid in focuses)
    return 'OR = { ' + terms + ' }' if len(focuses) > 1 else terms


def gate(row, focuses, mio=False):
    # PREV is the owning country after entering the literal state scope, including
    # when the owning country is entered through the MIO's documented FROM scope.
    body = (f'has_capitulated = no {completed(focuses)} '
            f'{row["factory_state"]} = {{ is_owned_by = PREV is_fully_controlled_by = PREV }}')
    return 'FROM = { ' + body + ' }' if mio else body


def stats_text(values):
    return '、'.join(STAT_NAMES[k] + (f'{v:+.0f}' if k == 'military_industrial_organization_task_capacity' else f'{v:+.0%}') for k, v in values.items())


def totals(row, design):
    result = {"equipment": dict(row['initial_equipment']), "production": dict(row['initial_production']),
              "organization": dict(design['initial_organization'])}
    for trait in row['traits']:
        for group in result:
            for stat, amount in trait.get(group, {}).items():
                result[group][stat] = round(result[group].get(stat, 0) + amount, 6)
    return result


def localized_focuses(row, field):
    return ' / '.join(row[field + '_names'])


