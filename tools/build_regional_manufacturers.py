def build(check_only=False):
    design = json.loads(DESIGN.read_text(encoding='utf-8'))
    rendered = render(design)
    for kind, relative in OUTPUTS.items():
        path = ROOT / relative
        encoding = 'utf-8-sig' if kind == 'loc' else 'utf-8'
        if check_only:
            assert path.read_text(encoding=encoding) == rendered[kind], relative
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered[kind], encoding=encoding, newline='\n')
    return len(design['manufacturers'])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print(json.dumps({'manufacturers': build(args.check), 'check_only': args.check}, ensure_ascii=False))
