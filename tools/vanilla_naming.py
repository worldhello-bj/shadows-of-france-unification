def removed_nodes(nodes,donor):
    from hoi4_script import entries
    reasons=dict(REMOVE_ROOTS[donor])
    while True:
        new={k:'前置分支已删除，无法在保留结构中到达' for k,b in nodes.items() if k not in reasons and any(parents and all(r.value in reasons for r in parents) for g in entries(b,'prerequisite') for parents in [entries(g.value,'focus')])}
        if not new:break
        reasons.update(new)
    return reasons
